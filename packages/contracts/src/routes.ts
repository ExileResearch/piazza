/** Reviewable intent derives from the actual eligible route inputs, excluding credentials/admin/binary. */
const approvalEligible = Object.entries(baseRoutes).filter(
  ([, route]) =>
    route.agent && route.method !== "GET" && route.representation !== "binary",
);
const intentVariants = approvalEligible.map(([operationId, route]) =>
  z.strictObject({
    operationId: z.literal(operationId),
    params: route.params,
    query: route.query,
    body: route.body,
  }),
);
export const actionIntentSchema = z.union(
  intentVariants as [(typeof intentVariants)[number], ...typeof intentVariants],
);
export const requestActionApprovalSchema = z.strictObject({
  intent: actionIntentSchema,
  budget: c.budgetCapsSchema,
});
export const actionApprovalDetailSchema = z.strictObject({
  approval: c.actionApprovalSchema,
  intent: actionIntentSchema,
});
export const apiRoutes = Object.freeze({
  ...baseRoutes,
  requestActionApproval: defineRoute(
    "POST",
    "/api/v1/action-approvals",
    requestActionApprovalSchema,
    c.emptySchema,
    actionApprovalDetailSchema,
    "scoped_approval_request",
    ["F02"],
    { status: 201 },
  ),
  actionApproval: defineRoute(
    "GET",
    "/api/v1/action-approvals/:id",
    c.emptySchema,
    c.emptySchema,
    actionApprovalDetailSchema,
    "participant",
    ["F02"],
  ),
});
export type ApiOperationId = keyof typeof apiRoutes;
export type RouteRequest<K extends ApiOperationId> = {
  params: z.input<(typeof apiRoutes)[K]["params"]>;
  query: z.input<(typeof apiRoutes)[K]["query"]>;
  body: z.input<(typeof apiRoutes)[K]["body"]>;
  headers: z.input<(typeof apiRoutes)[K]["headers"]>;
};
export type RouteResponse<K extends ApiOperationId> = z.output<
  (typeof apiRoutes)[K]["response"]
>;
export type ActionIntent = z.infer<typeof actionIntentSchema>;
export type RequestActionApproval = z.infer<typeof requestActionApprovalSchema>;
export type ActionApprovalDetail = z.infer<typeof actionApprovalDetailSchema>;
